-- =====================================================================
-- USERS schema (Oracle). Port of the Postgres design in the TDD §9.1.
--   UUID      -> RAW(16)  (the same mapping the other services use)
--   TIMESTAMPTZ -> TIMESTAMP WITH TIME ZONE
--   BOOLEAN   -> NUMBER(1)
--   partial unique indexes -> unique index on a virtual column that is NULL for rows to ignore
-- =====================================================================
CREATE TABLE users (
    id                 RAW(16) DEFAULT SYS_GUID() NOT NULL,
    email              VARCHAR2(255 CHAR) NOT NULL,
    phone              VARCHAR2(20 CHAR),
    first_name         VARCHAR2(80 CHAR)  NOT NULL,
    last_name          VARCHAR2(80 CHAR),
    status             VARCHAR2(20 CHAR)  DEFAULT 'PENDING_VERIFICATION' NOT NULL,
    email_verified_at  TIMESTAMP WITH TIME ZONE,
    phone_verified_at  TIMESTAMP WITH TIME ZONE,
    last_login_at      TIMESTAMP WITH TIME ZONE,
    locale             VARCHAR2(10 CHAR)  DEFAULT 'en-IN' NOT NULL,
    version            NUMBER(19)         DEFAULT 0 NOT NULL,
    created_at         TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at         TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    deleted_at         TIMESTAMP WITH TIME ZONE,
    -- only live (not deleted) rows take part in the uniqueness rules below
    active_email_key   VARCHAR2(255 CHAR) GENERATED ALWAYS AS (CASE WHEN deleted_at IS NULL THEN LOWER(email) END),
    active_phone_key   VARCHAR2(20 CHAR)  GENERATED ALWAYS AS (CASE WHEN deleted_at IS NULL THEN phone END),
    CONSTRAINT pk_users PRIMARY KEY (id),
    CONSTRAINT ck_users_status CHECK (status IN ('PENDING_VERIFICATION','ACTIVE','SUSPENDED','DELETED'))
);
CREATE UNIQUE INDEX uq_users_email ON users (active_email_key);
CREATE UNIQUE INDEX uq_users_phone ON users (active_phone_key);
CREATE INDEX idx_users_status ON users (status);

CREATE TABLE password_credentials (
    user_id          RAW(16) NOT NULL,
    password_hash    VARCHAR2(255 CHAR) NOT NULL,
    algorithm        VARCHAR2(20 CHAR)  DEFAULT 'BCRYPT' NOT NULL,
    failed_attempts  NUMBER(10)         DEFAULT 0 NOT NULL,
    locked_until     TIMESTAMP WITH TIME ZONE,
    updated_at       TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_password_credentials PRIMARY KEY (user_id),
    CONSTRAINT fk_pwd_cred_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE TABLE roles (
    id    NUMBER(5) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    code  VARCHAR2(40 CHAR) NOT NULL,
    label VARCHAR2(80 CHAR) NOT NULL,
    CONSTRAINT pk_roles PRIMARY KEY (id),
    CONSTRAINT uq_roles_code UNIQUE (code)
);
