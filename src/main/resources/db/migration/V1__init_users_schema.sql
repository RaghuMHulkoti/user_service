CREATE TABLE user_roles (
    user_id    RAW(16)   NOT NULL,
    role_id    NUMBER(5) NOT NULL,
    granted_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_user_roles PRIMARY KEY (user_id, role_id),
    CONSTRAINT fk_user_roles_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_user_roles_role FOREIGN KEY (role_id) REFERENCES roles (id)
);

CREATE TABLE addresses (
    id           RAW(16) DEFAULT SYS_GUID() NOT NULL,
    user_id      RAW(16) NOT NULL,
    label        VARCHAR2(40 CHAR),
    line1        VARCHAR2(200 CHAR) NOT NULL,
    line2        VARCHAR2(200 CHAR),
    city         VARCHAR2(100 CHAR) NOT NULL,
    state        VARCHAR2(100 CHAR) NOT NULL,
    postal_code  VARCHAR2(20 CHAR)  NOT NULL,
    country      VARCHAR2(2 CHAR)   NOT NULL,
    is_default   NUMBER(1) DEFAULT 0 NOT NULL CHECK (is_default IN (0, 1)),
    geo_lat      NUMBER(9,6),
    geo_lng      NUMBER(9,6),
    version      NUMBER(19) DEFAULT 0 NOT NULL,
    created_at   TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at   TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    -- set only on the default address, so the unique index allows one default per user
    default_owner_key RAW(16) GENERATED ALWAYS AS (CASE WHEN is_default = 1 THEN user_id END),
    CONSTRAINT pk_addresses PRIMARY KEY (id),
    CONSTRAINT fk_addresses_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);
CREATE INDEX idx_addresses_user ON addresses (user_id);
CREATE UNIQUE INDEX uq_addresses_default_per_user ON addresses (default_owner_key);

CREATE TABLE payment_method_tokens (
    id             RAW(16) DEFAULT SYS_GUID() NOT NULL,
    user_id        RAW(16) NOT NULL,
    provider       VARCHAR2(20 CHAR)  NOT NULL,           -- STRIPE | RAZORPAY
    provider_token VARCHAR2(255 CHAR) NOT NULL,           -- pm_xxx (NEVER raw PAN)
    brand          VARCHAR2(20 CHAR),                     -- VISA, MC...
    last4          VARCHAR2(4 CHAR),
    exp_month      NUMBER(2),
    exp_year       NUMBER(4),
    is_default     NUMBER(1) DEFAULT 0 NOT NULL CHECK (is_default IN (0, 1)),
    created_at     TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_payment_method_tokens PRIMARY KEY (id),
    CONSTRAINT fk_pmt_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);
CREATE INDEX idx_pmt_user ON payment_method_tokens (user_id);

CREATE TABLE email_verifications (
    id          RAW(16) DEFAULT SYS_GUID() NOT NULL,
    user_id     RAW(16) NOT NULL,
    token_hash  VARCHAR2(64 CHAR) NOT NULL,               -- SHA-256 hex
    expires_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    consumed_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT pk_email_verifications PRIMARY KEY (id),
    CONSTRAINT fk_email_verif_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);
CREATE INDEX idx_email_verif_user ON email_verifications (user_id);

CREATE TABLE consent_log (
    id         NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    user_id    RAW(16) NOT NULL,
    kind       VARCHAR2(40 CHAR) NOT NULL,                -- MARKETING_EMAIL, COOKIES, ...
    granted    NUMBER(1) NOT NULL CHECK (granted IN (0, 1)),
    ip         VARCHAR2(45 CHAR),                         -- IPv4 or IPv6 text
    created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_consent_log PRIMARY KEY (id),
    CONSTRAINT fk_consent_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);
CREATE INDEX idx_consent_user ON consent_log (user_id, kind);

CREATE TABLE user_outbox (
    id            NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    aggregate_id  RAW(16)           NOT NULL,
    event_type    VARCHAR2(60 CHAR) NOT NULL,
    payload       CLOB              NOT NULL,
    headers       CLOB,
    status        VARCHAR2(20 CHAR) DEFAULT 'PENDING' NOT NULL,   -- PENDING|SENT|FAILED
    created_at    TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    sent_at       TIMESTAMP WITH TIME ZONE,
    CONSTRAINT pk_user_outbox PRIMARY KEY (id),
    CONSTRAINT ck_user_outbox_payload CHECK (payload IS JSON),
    CONSTRAINT ck_user_outbox_headers CHECK (headers IS JSON)
);
CREATE INDEX idx_user_outbox_pending ON user_outbox (status, created_at);
